"""Amateurfunkbaender (IARU Region 1) und Hilfsfunktionen."""

# (Band, von Hz, bis Hz, Startfrequenz fuer Bandtaste)
BANDS = [
    ("160m", 1_810_000, 2_000_000, 1_840_000),
    ("80m", 3_500_000, 3_800_000, 3_573_000),
    ("60m", 5_351_500, 5_366_500, 5_357_000),
    ("40m", 7_000_000, 7_200_000, 7_074_000),
    ("30m", 10_100_000, 10_150_000, 10_136_000),
    ("20m", 14_000_000, 14_350_000, 14_074_000),
    ("17m", 18_068_000, 18_168_000, 18_100_000),
    ("15m", 21_000_000, 21_450_000, 21_074_000),
    ("12m", 24_890_000, 24_990_000, 24_915_000),
    ("10m", 28_000_000, 29_700_000, 28_074_000),
    ("6m", 50_000_000, 52_000_000, 50_313_000),
    ("4m", 70_000_000, 70_500_000, 70_154_000),
    ("2m", 144_000_000, 146_000_000, 144_174_000),
    ("70cm", 430_000_000, 440_000_000, 432_174_000),
    ("23cm", 1_240_000_000, 1_300_000_000, 1_296_174_000),
]


def band_for(hz: float | int | None) -> str:
    if not hz:
        return ""
    for name, lo, hi, _ in BANDS:
        if lo <= hz <= hi:
            return name
    return ""


def default_rst(mode: str) -> str:
    m = (mode or "").upper()
    if m in ("CW", "CWR", "RTTY", "RTTYR", "PSK31", "PSK"):
        return "599"
    if m in ("FT8", "FT4", "JT65", "JT9", "MSK144", "Q65", "PKTUSB", "PKTLSB", "DATA"):
        return "-10"
    return "59"
